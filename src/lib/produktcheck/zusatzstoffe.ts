const KATALOG = new Map<string, Zusatzstoff>(
  DATEN.map(([code, name, funktion, stufe, risiken, text]) => [
    code,
    { code, name, funktion, stufe, risiken: risiken ? (risiken.split(',').filter(Boolean) as Risiko[]) : [], text },
  ]),
)

/** 'en:e330', 'E330' oder 'e330' → Eintrag; unbekannte E-Nummern werden als „nicht bewertet“ geliefert */
export function zusatzstoff(tag: string): Zusatzstoff & { bekannt: boolean } {
  const code = tag.toLowerCase().replace(/^[a-z]{2}:/, '').replace(/\s+/g, '')
  // Unterarten wie 'e322i' oder 'e160aii' auf den Haupteintrag zurückführen
  const eintrag = KATALOG.get(code) ?? KATALOG.get(code.replace(/i+$/, '')) ?? KATALOG.get(code.replace(/[a-z]+$/, ''))
  if (eintrag) return { ...eintrag, bekannt: true }
  return { code, name: code.toUpperCase(), funktion: 'sonstiges', stufe: 0, risiken: [], bekannt: false }
}

export function codeAnzeige(code: string): string {
  return code.toUpperCase()
}
